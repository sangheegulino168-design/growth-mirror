const t = (key) => translations[currentLocale][key] ?? key;

function applyLanguage() {
  document.documentElement.lang = currentLocale;
  document.querySelectorAll("[data-i18n]").forEach((element) => { element.textContent = t(element.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => { element.placeholder = t(element.dataset.i18nPlaceholder); });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => { element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel)); });
  document.querySelectorAll("[data-result-key]").forEach((element) => { element.textContent = t(element.dataset.resultKey); });
  document.querySelectorAll(".lang-button").forEach((button) => button.classList.toggle("active", button.dataset.lang === currentLocale));
  const intensity = Number($("#contextIntensity").value);
  $("#intensityOutput").textContent = intensity < .4 ? t("low") : intensity < .8 ? t("medium") : t("high");
  updateServiceStatus();
}

function updateServiceStatus() {
  if (serviceState === "online") {
    $("#serviceStatus").textContent = `${t("connected")} · ${serviceModelMode}`;
  } else if (serviceState === "offline") {
    $("#serviceStatus").textContent = t("unavailable");
  } else {
    $("#serviceStatus").textContent = t("connecting");
  }
}

async function api(path, options = {}) {
  const response = await fetch(`${API_BASE}${path}`, { headers: { "Content-Type": "application/json" }, ...options });
  const body = await response.json();
  if (!response.ok) {
    const error = new Error(body.detail || "请求失败");
    error.status = response.status;
    throw error;
  }
  return body;
}

function setBusy(button, busy) {
  button.disabled = busy;
  button.dataset.original ||= button.textContent;
  button.textContent = busy ? t("processing") : t(button.dataset.i18n || button.dataset.original);
}

function addMessage(text, role) {
  const item = document.createElement("div");
  item.className = `message ${role}`;
  item.textContent = text;
  $("#messages").appendChild(item);
  item.scrollIntoView({ behavior: "smooth", block: "end" });
}

function renderScenario() {
  if (!state.childId) return;
  const eligible = scenarios.filter(
    (scenario) => state.ageYears >= scenario.minAge && state.ageYears <= scenario.maxAge
  );
  const pool = eligible.length ? eligible : scenarios;
  const index = (state.eventCount + state.scenarioOffset) % pool.length;
  state.currentScenario = pool[index];
  const content = state.currentScenario[currentLocale];
  $("#scenarioChapter").textContent = `${t("sceneLabel")} ${state.eventCount + 1} · ${content.phase}`;
  $("#scenarioTitle").textContent = content.title;
  $("#scenarioBody").textContent = content.body;
  $("#scenarioSpeech").textContent = `“${content.speech}”`;
  $("#stageLabel").textContent = content.phase;
  document.querySelectorAll(".prompt-chip").forEach((button) => {
    button.textContent = content.prompts[Number(button.dataset.promptIndex)];
    button.classList.remove("selected");
  });
  $("#chatInput").placeholder = t("chatPlaceholder");
}

function scenarioTraceText(scenario, locale) {
  const content = scenario[locale];
  return `${content.title}\n${content.body}\n${content.speech}`;
}

function bar(name, value) {
  const row = document.createElement("div");
  row.className = "bar-row";
  row.innerHTML = `<span>${translations[currentLocale].traits[name] || name}</span><div class="bar-track"><div class="bar-fill" style="width:${Math.round(value * 100)}%"></div></div><b>${Math.round(value * 100)}</b>`;
  return row;
}

async function refreshChild() {
  if (!state.childId) return;
  try {
    const child = await api(`/children/${state.childId}`);
    $("#onboarding").classList.add("hidden");
    $("#workspace").classList.remove("hidden");
    $("#displayName").textContent = child.name;
    state.childName = child.name;
    state.ageYears = child.age_years;
    state.eventCount = child.event_count;
    $("#ageValue").textContent = currentLocale === "en" ? `${child.age_years} yrs` : `${child.age_years} 岁`;
    $("#eventCount").textContent = child.event_count;
    $("#contextCount").textContent = child.environment_event_count;
    const traits = $("#traitBars"); traits.innerHTML = "";
    Object.entries(child.traits).forEach(([name, value]) => traits.appendChild(bar(name, value)));
    const context = $("#contextBars"); context.innerHTML = "";
    ["relationship_safety", "stress_load", "social_belonging", "future_outlook"].forEach((name) => context.appendChild(bar(name, child[name])));
    renderScenario();
  } catch (error) {
    // Only a confirmed 404 means that the saved child no longer exists. A
    // transient startup/network error must never erase a long-term identity.
    if (error.status !== 404) throw error;
    localStorage.removeItem("growthMirrorChildId");
    state.childId = null;
    state.childName = "";
    $("#onboarding").classList.remove("hidden");
    $("#workspace").classList.add("hidden");
  }
}

async function refreshReport() {
  if (!state.childId) return;
  const container = $("#reportContent");
  container.textContent = t("organizing");
  try {
    const report = await api(`/children/${state.childId}/report?locale=${encodeURIComponent(currentLocale)}`);
    const items = [...report.observations, ...report.context_observations];
    container.innerHTML = "";
    if (!items.length) { container.textContent = t("insufficient"); return; }
    items.forEach((item) => {
      const card = document.createElement("div"); card.className = "report-card";
      const evidenceCount = (item.evidence_event_ids || []).length;
      const recordLabel = evidenceCount === 1 ? t("traceableOne") : t("traceable");
      card.innerHTML = `<strong>${item.observation}</strong><small>${currentLocale === "en" ? "Based on" : "基于"} ${evidenceCount} ${recordLabel} · ${t("confidence")} ${Math.round(item.confidence * 100)}%</small><small>${item.reflection_question || item.attribution_note || ""}</small>`;
      container.appendChild(card);
    });
  } catch (error) { container.textContent = error.message; }
}

$("#createForm").addEventListener("submit", async (event) => {
  event.preventDefault(); const button = event.submitter; setBusy(button, true);
  try {
    const child = await api("/children", { method: "POST", body: JSON.stringify({ name: $("#childName").value.trim(), temperament_seed: Number($("#seed").value), age_years: Number($("#initialAge").value) }) });
    state.childId = child.child_id; localStorage.setItem("growthMirrorChildId", state.childId); await refreshChild();
  } catch (error) { alert(error.message); } finally { setBusy(button, false); }
});

